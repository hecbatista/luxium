package io.github.hecbatista.metalshaders.mixin;

import com.llamalad7.mixinextras.injector.wrapoperation.Operation;
import com.llamalad7.mixinextras.injector.wrapoperation.WrapOperation;
import com.mojang.renderpearl.api.pipeline.CompiledRenderPipeline;
import com.mojang.renderpearl.api.pipeline.RenderPipeline;
import io.github.hecbatista.metalshaders.render.EntityTakeover;
import net.minecraft.client.renderer.WeatherEffectRenderer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;

/** The weather's pipeline (WeatherEffectRenderer.render, 26.3) swapped for the pack's while it's routed. */
@Mixin(WeatherEffectRenderer.class)
abstract class WeatherEffectRendererMixin {
    @WrapOperation(method = "render(Lnet/minecraft/client/renderer/state/level/WeatherRenderState;Lcom/mojang/renderpearl/api/commands/RenderPass;Lcom/mojang/renderpearl/api/pipeline/RenderPipeline;)V",
            at = @At(value = "INVOKE",
            target = "Lcom/mojang/blaze3d/systems/RenderSystem;getCompiledPipeline(Lcom/mojang/renderpearl/api/pipeline/RenderPipeline;)Lcom/mojang/renderpearl/api/pipeline/CompiledRenderPipeline;"))
    private CompiledRenderPipeline luxium$weatherPipeline(final RenderPipeline pipeline, final Operation<CompiledRenderPipeline> original) {
        return EntityTakeover.particlePipelineFor(pipeline, original.call(pipeline));
    }
}
